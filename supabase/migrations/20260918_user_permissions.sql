-- Controle administrativo de usuários, módulos, indicadores e ações.
-- Não recria nem apaga dados de negócio; apenas acrescenta relações e políticas.

CREATE TABLE IF NOT EXISTS public.sustentacao_usuario_modulos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  operacao_id bigint NOT NULL REFERENCES public.sustentacao_operacoes(id) ON DELETE CASCADE,
  modulo text NOT NULL CHECK (modulo IN ('PLANO_SUSTENTACAO','SLA_NEOLOG','ABSENTEISMO','PLANO_ACAO','INVENTARIOS')),
  pode_visualizar boolean NOT NULL DEFAULT false,
  pode_editar boolean NOT NULL DEFAULT false,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sustentacao_usuario_modulos_unique UNIQUE (user_id, operacao_id, modulo),
  CONSTRAINT sustentacao_usuario_modulos_edit_view_check CHECK (pode_editar = false OR pode_visualizar = true)
);

CREATE TABLE IF NOT EXISTS public.sustentacao_usuario_indicadores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  operacao_id bigint NOT NULL REFERENCES public.sustentacao_operacoes(id) ON DELETE CASCADE,
  indicador_id bigint NOT NULL,
  pode_visualizar boolean NOT NULL DEFAULT false,
  pode_editar boolean NOT NULL DEFAULT false,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sustentacao_usuario_indicadores_unique UNIQUE (user_id, operacao_id, indicador_id),
  CONSTRAINT sustentacao_usuario_indicadores_edit_view_check CHECK (pode_editar = false OR pode_visualizar = true)
);

CREATE TABLE IF NOT EXISTS public.sustentacao_usuario_plano_acao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  operacao_id bigint NOT NULL REFERENCES public.sustentacao_operacoes(id) ON DELETE CASCADE,
  pode_visualizar boolean NOT NULL DEFAULT false,
  pode_criar boolean NOT NULL DEFAULT false,
  pode_editar boolean NOT NULL DEFAULT false,
  pode_alterar_status boolean NOT NULL DEFAULT false,
  pode_concluir boolean NOT NULL DEFAULT false,
  pode_excluir boolean NOT NULL DEFAULT false,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sustentacao_usuario_plano_acao_unique UNIQUE (user_id, operacao_id),
  CONSTRAINT sustentacao_usuario_plano_acao_view_check CHECK (
    pode_visualizar = true OR NOT (pode_criar OR pode_editar OR pode_alterar_status OR pode_concluir OR pode_excluir)
  )
);

CREATE TABLE IF NOT EXISTS public.sustentacao_auditoria_permissoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ator_user_id uuid NOT NULL REFERENCES auth.users(id),
  alvo_user_id uuid NOT NULL REFERENCES auth.users(id),
  operacao_id bigint REFERENCES public.sustentacao_operacoes(id),
  tipo_alteracao text NOT NULL,
  permissoes_anteriores jsonb NOT NULL DEFAULT '{}'::jsonb,
  permissoes_novas jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);


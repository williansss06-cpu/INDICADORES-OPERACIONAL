      FOREIGN KEY (indicador_id, operacao_id)
      REFERENCES public.sustentacao_indicadores (id, operacao_id);
  END IF;
END $$;

-- Liga as linhas SLA existentes aos indicadores GLP sem alterar ano, mês, tipo ou valor.
UPDATE public.sustentacao_sla_neolog_pontuacoes s
SET indicador_id = i.id,
    updated_at = now()
FROM public.sustentacao_indicadores i
WHERE s.operacao_id = i.operacao_id
  AND i.operacao_id = (SELECT id FROM public.sustentacao_operacoes WHERE codigo = 'GLP_ACHE' LIMIT 1)
  AND i.nome = CASE
    WHEN s.indicador = 'Ocorrências Fora do Prazo' THEN 'Ocorrências Monitoramento'
    ELSE s.indicador
  END
  AND s.indicador_id IS NULL;


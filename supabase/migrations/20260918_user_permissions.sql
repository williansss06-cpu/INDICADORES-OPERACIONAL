DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'sustentacao_indicadores_id_operacao_key'
      AND conrelid = 'public.sustentacao_indicadores'::regclass
  ) THEN
    ALTER TABLE public.sustentacao_indicadores

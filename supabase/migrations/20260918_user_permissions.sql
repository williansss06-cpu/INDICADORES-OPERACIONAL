      FOREIGN KEY (indicador_id, operacao_id)
      REFERENCES public.sustentacao_indicadores (id, operacao_id)
      ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'sustentacao_plano_acao_indicator_operation_fkey'
      AND conrelid = 'public.sustentacao_plano_acao'::regclass
  ) THEN
    ALTER TABLE public.sustentacao_plano_acao
      ADD CONSTRAINT sustentacao_plano_acao_indicator_operation_fkey
      FOREIGN KEY (indicador_id, operacao_id)
      REFERENCES public.sustentacao_indicadores (id, operacao_id);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'sustentacao_plano_acao_responsavel_user_fkey'
      AND conrelid = 'public.sustentacao_plano_acao'::regclass
  ) THEN
    ALTER TABLE public.sustentacao_plano_acao
      ADD CONSTRAINT sustentacao_plano_acao_responsavel_user_fkey
      FOREIGN KEY (responsavel_user_id)
      REFERENCES auth.users (id)
      ON DELETE SET NULL;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'sustentacao_sla_indicator_operation_fkey'
      AND conrelid = 'public.sustentacao_sla_neolog_pontuacoes'::regclass
